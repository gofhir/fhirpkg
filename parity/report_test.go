// El reporte de la paridad: lo escriben los tests, no se copia a mano.
// PARITY_REPORT es el archivo (docs/evidence/<fecha>-parity.md) y PARITY_ISSUE
// el borrador de docs/issues/models-fhirpath-model-gaps.md, cuyo bloque entre
// las marcas se reescribe con las cifras.

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"sync"
	"testing"

	"github.com/gofhir/fhirpkg"
)

var (
	repMu  sync.Mutex
	repCls *classified
)

func setClassified(c *classified) {
	repMu.Lock()
	repCls = c
	repMu.Unlock()
}

func TestMain(m *testing.M) {
	code := m.Run()
	if code == 0 && !benchOff() {
		if path := os.Getenv("PARITY_REPORT"); path != "" {
			if err := os.WriteFile(path, []byte(renderReport()), 0o644); err != nil {
				fmt.Fprintln(os.Stderr, err)
				code = 1
			}
		}
		if path := os.Getenv("PARITY_ISSUE"); path != "" {
			if err := updateIssue(path); err != nil {
				fmt.Fprintln(os.Stderr, err)
				code = 1
			}
		}
	}
	os.Exit(code)
}

var versionNames = []string{"R4", "R4B", "R5"}

func counts(m map[string]int) string {
	parts := make([]string, len(versionNames))
	for i, v := range versionNames {
		parts[i] = fmt.Sprint(m[v])
	}
	return strings.Join(parts, " / ")
}

// tableSummary: por tabla, las claves de cada parte y las diferencias, por versión.
func tableSummary(cl *classified) string {
	var b strings.Builder
	b.WriteString("| Table | Keys in models (R4 / R4B / R5) | Keys in fhirpkg | Differences |\n| --- | --- | --- | --- |\n")
	for _, tb := range tables {
		var km, ko, df []string
		for _, v := range versionNames {
			k := cl.keys[v][tb.name]
			km, ko = append(km, fmt.Sprint(k[0])), append(ko, fmt.Sprint(k[1]))
			df = append(df, fmt.Sprint(cl.totals[v][tb.name]))
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", tb.name, strings.Join(km, " / "), strings.Join(ko, " / "), strings.Join(df, " / "))
	}
	return b.String()
}

func classSummary(cl *classified) string {
	var b strings.Builder
	b.WriteString("| Class | Kind | Count (R4 / R4B / R5) | Classification | Reference |\n| --- | --- | --- | --- | --- |\n")
	for _, c := range cl.classes {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", c.ID, c.Kind, counts(cl.got[c.ID]), c.Class, c.Reference)
	}
	return b.String()
}

func renderReport() string {
	repMu.Lock()
	cl := repCls
	repMu.Unlock()
	var b strings.Builder
	b.WriteString("# Parity of the type model with gofhir/models\n\nGenerated by `make parity` (module `parity/`): gofhir/models v2.10.0 (r4, r4b, r5) against `fhirpkg.Model`, with the official core packages of the locks in `testdata/`. Every difference is classified in `parity/testdata/differences.json`; the test fails on an unclassified one, on one that belongs to two classes and on a class whose count changes.\n\n")
	if cl != nil {
		b.WriteString("## The nine tables\n\n" + tableSummary(cl) + "\n## Classes of difference\n\n" + classSummary(cl) + "\n")
		for _, c := range cl.classes {
			fmt.Fprintf(&b, "- `%s` (%s): %s\n", c.ID, c.Class, c.Reason)
		}
		b.WriteString("\n")
	}
	b.WriteString("## searchindex.Extract on the official examples\n\n| FHIR | Examples | Same index with both models | Different |\n| --- | --- | --- | --- |\n")
	for _, v := range versionNames {
		if s := siStats[v]; s != nil {
			fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", v, s.Examples, s.Same, len(s.Diffs))
		}
	}
	b.WriteString("\n## fhirpath: is, as, type(), children() and Analyze\n\n| FHIR | Examples | Evaluations | Different | Explained by `nested-backbone-type` | Package expressions analyzed | Analyze differs |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, v := range versionNames {
		if s := fpStats[v]; s != nil {
			fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d |\n", v, s.Examples, s.Evaluations, s.Different, s.Explained, s.AnalyzeExpressions, s.AnalyzeDifferent)
		}
	}
	b.WriteString("\nThe Analyze differences are the known loss of H1 ([fhirpath-analyze-abstract-types](../issues/fhirpath-analyze-abstract-types.md)); the model is not changed to avoid it.\n")
	b.WriteString(renderNormalizer())
	if len(benchRows) > 0 {
		sort.Slice(benchRows, func(i, j int) bool { return benchRows[i].Name < benchRows[j].Name })
		b.WriteString("\n## Benchmark with both models already built\n\nInformative, no thresholds. `Extract` is one pass over a sample of two examples per resource type; `Lookups` is the model queries of one evaluation.\n\n| Benchmark | ns/op | allocs/op | B/op |\n| --- | --- | --- | --- |\n")
		for _, r := range benchRows {
			fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", r.Name, r.NsPerOp, r.AllocsPerOp, r.BytesPerOp)
		}
	}
	return b.String()
}

// updateIssue reescribe el bloque generado del borrador del issue de models.
func updateIssue(path string) error {
	repMu.Lock()
	cl := repCls
	repMu.Unlock()
	if cl == nil {
		return nil
	}
	const begin, end = "<!-- parity:begin -->", "<!-- parity:end -->"
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(raw)
	i, j := strings.Index(s, begin), strings.Index(s, end)
	if i < 0 || j < i {
		return fmt.Errorf("%s: the parity markers are missing", path)
	}
	var b strings.Builder
	b.WriteString(begin + "\n\nCounts generated by the parity of fhirpkg (`make parity`, R4 / R4B / R5); not edited by hand.\n\n")
	var ids []string
	for _, c := range cl.classes {
		if c.Class == classModelsDefect {
			ids = append(ids, c.ID)
		}
	}
	sort.Strings(ids)
	for _, id := range ids {
		for _, c := range cl.classes {
			if c.ID == id {
				fmt.Fprintf(&b, "- **%s** (%s): %s differences in R4 / R4B / R5. %s\n", c.ID, strings.Join(c.Tables, ", "), counts(cl.got[c.ID]), c.Reason)
			}
		}
	}
	b.WriteString("\n" + end)
	return os.WriteFile(path, []byte(s[:i]+b.String()+s[j+len(end):]), 0o644)
}

// renderNormalizer es la sección del normalizador (plan 004): la paridad por
// fuente y clase, el anidamiento medido y el benchmark contra models.
func renderNormalizer() string {
	npMu.Lock()
	stats, rows := append([]normStat(nil), npStats...), append([]parityCount(nil), npRows...)
	npMu.Unlock()
	nbMu.Lock()
	bench := append([]benchRowN(nil), nbRows...)
	nbMu.Unlock()
	if len(stats) == 0 && len(bench) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("\n## Normalizer (`Context.Normalize`) against gofhir/models\n\n")
	if len(stats) > 0 {
		b.WriteString("Every resource goes through `Normalize` and through `UnmarshalResource` + `Marshal` of models; the class of each one is in `parity/testdata/normalizer.json` (counts fixed; the test fails on an unclassified resource or a count that changes). `probes` are the hand-written inputs for the classes that no corpus exercises. Reordered: the output differs from the input and still equals what models writes.\n\n")
		b.WriteString("| Source | FHIR | Resources | MB | Unchanged and reordered | Max nesting (objects and arrays, root = 1) |\n| --- | --- | --- | --- | --- | --- |\n")
		sort.Slice(stats, func(i, j int) bool {
			return stats[i].Source+stats[i].Version < stats[j].Source+stats[j].Version
		})
		for _, s := range stats {
			nest := fmt.Sprint(s.MaxDepth)
			if s.Source == "probes" {
				nest = "-"
			}
			fmt.Fprintf(&b, "| %s | %s | %d | %d | %d | %s |\n", s.Source, s.Version, s.Resources, s.Bytes>>20, s.Reordered, nest)
		}
		fmt.Fprintf(&b, "\nDefault depth limit of `Normalize`: %d (`fhirpkg.DefaultMaxDepth`); the test requires at least twice the measured maximum.\n\n", fhirpkg.DefaultMaxDepth)
		type k struct{ src, class, rule string }
		agg := map[k]map[string]int{}
		var order []k
		for _, r := range rows {
			key := k{r.Source, r.Class, r.Rule}
			if agg[key] == nil {
				agg[key] = map[string]int{}
				order = append(order, key)
			}
			agg[key][r.Version] = r.Count
		}
		sort.Slice(order, func(i, j int) bool { return fmt.Sprint(order[i]) < fmt.Sprint(order[j]) })
		b.WriteString("| Source | Class | Rule | Count (R4 / R4B / R5) |\n| --- | --- | --- | --- |\n")
		for _, key := range order {
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", key.src, key.class, key.rule, counts(agg[key]))
		}
	}
	if len(bench) > 0 {
		b.WriteString("\n### Benchmark: Normalize against models UnmarshalResource + Marshal\n\nInformative, no thresholds. Time and allocations from `testing.Benchmark` (one process, warm); RSS is the maximum of a child process per measurement minus its base (the example in memory, and the Context for fhirpkg), in MB, with a noise of a few MB.\n\n| FHIR | Example | Bytes | Implementation | ms/op | allocs/op | B/op | RSS MB |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
		sort.Slice(bench, func(i, j int) bool {
			a, c := bench[i], bench[j]
			if a.Version != c.Version {
				return a.Version < c.Version
			}
			if a.Size != c.Size {
				return a.Size < c.Size
			}
			return a.Impl < c.Impl
		})
		for _, r := range bench {
			if r.Err != "" {
				fmt.Fprintf(&b, "| %s | %s | %d | %s | fails: %s | | | |\n", r.Version, r.Example, r.Size, r.Impl, r.Err)
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | %d | %s | %.2f | %d | %d | %d |\n", r.Version, r.Example, r.Size, r.Impl, float64(r.NsPerOp)/1e6, r.AllocsPerOp, r.BytesPerOp, r.RSSMB)
		}
	}
	b.WriteString(renderRetention())
	return b.String()
}
