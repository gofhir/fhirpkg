#!/usr/bin/env bash
# Genera docs/evidence/<fecha>-<hora>.md con el commit, el estado del árbol,
# cada comando de validación con su código de salida, duración, RSS máximo y las
# líneas de resumen de su salida (las que los tests registran con t.Logf). Si
# algún comando falla, el reporte lo dice y el script termina con error.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
cd "$here"
scripts/fetch-packages.sh >/dev/null
stamp=$(date +%Y-%m-%d-%H%M)
out=docs/evidence/$stamp.md
mkdir -p docs/evidence
pk=$here/.cache/packages
failed=0
dirty=$(git status --porcelain)

# El RSS es el del proceso más grande del paso, no la suma. /usr/bin/time da el
# RSS en bytes con -l (macOS) y en KB con -v (Linux).
case $(uname) in
  Darwin) timeflag=-l rss_re='maximum resident set size' rss_div=1048576 ;;
  *) timeflag=-v rss_re='Maximum resident set size' rss_div=1024 ;;
esac

run() {
  local title=$1 cmd=$2 status log tlog start secs rss
  log=$(mktemp)
  tlog=$(mktemp)
  start=$SECONDS
  set +e
  /usr/bin/time $timeflag bash -c "$cmd" >"$log" 2>"$tlog"
  status=$?
  set -e
  secs=$((SECONDS - start))
  rss=$(grep "$rss_re" "$tlog" | grep -Eo '[0-9]+' | head -1)
  grep -v -e "$rss_re" "$tlog" >>"$log" || true
  [[ $status -eq 0 ]] || failed=1
  {
    echo "## $title"
    echo
    echo "Command: \`$cmd\` · exit status: $status · ${secs} s · max RSS $((${rss:-0} / rss_div)) MB"
    echo
    echo '```text'
    grep -E -e '^(--- |ok |FAIL|PASS|panic)' -e '_test\.go:[0-9]+: ' -e '\.lock: FHIR' -e 'conflicts: ' "$log" | sed -E 's/^ +//' || true
    echo '```'
    echo
  } >>"$out"
  rm -f "$log" "$tlog"
}

{
  echo "# Evidence $stamp"
  echo
  echo "Generated by \`make evidence\` at commit \`$(git rev-parse --short HEAD 2>/dev/null || echo none)\` with $(go env GOVERSION)."
  if [[ -n $dirty ]]; then
    echo
    echo "**Uncommitted changes** (git status --porcelain):"
    echo
    echo '```text'
    echo "$dirty"
    echo '```'
  fi
  echo
} >"$out"

bin=$(mktemp -d)/fhirpkg
go build -o "$bin" ./cmd/fhirpkg
run "make check" "make check"
run "official packages (make check-packages)" "FHIRPKG_PACKAGES=$pk go test -count=1 -v -run TestReal ."
for lock in testdata/*.lock; do
  run "Open without network: $lock" "$bin verify -lock $lock -dir $pk"
done
# NewContext (plan 002): tiempo, heap y RSS máximo de Open + NewContext por versión.
for lock in testdata/r4.lock testdata/r4b.lock testdata/r5.lock; do
  run "Open and NewContext: $lock" "$bin context -lock $lock -dir $pk"
done
# Paridad del modelo de tipos (plan 003): las nueve tablas contra models, el
# diferencial de searchindex y de fhirpath, y el benchmark con los dos modelos.
# Su reporte es docs/evidence/<fecha>-parity.md.
run "type model parity (make parity)" "make parity"
if [[ $failed -ne 0 ]]; then
  echo "**At least one command failed.**" >>"$out"
  echo "$out: at least one command failed" >&2
  exit 1
fi
echo "$out"
