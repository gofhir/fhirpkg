package main

import (
	"bufio"
	"context"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/gofhir/fhirpkg"
)

type candidate struct {
	label string
	roots []string
}

// readCandidates lee un archivo con una raíz candidata por línea:
// "etiqueta | name#version name#version ...". Las líneas vacías y las que
// empiezan con # se ignoran.
func readCandidates(file string) ([]candidate, error) {
	f, err := os.Open(file)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []candidate
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		label, roots, ok := strings.Cut(line, "|")
		if !ok || strings.TrimSpace(label) == "" || len(strings.Fields(roots)) == 0 {
			return nil, fmt.Errorf("%s:%d: expected \"label | root root ...\"", file, n)
		}
		out = append(out, candidate{strings.TrimSpace(label), strings.Fields(roots)})
	}
	return out, sc.Err()
}

// pkgData es lo que se lee una sola vez de cada package, aunque aparezca en
// varios candidatos.
type pkgData struct {
	recs  []fhirpkg.URLRecord
	stats fhirpkg.PackageStats
}

func runGraph(args []string) error {
	fs := flag.NewFlagSet("graph", flag.ExitOnError)
	file := fs.String("candidates", "scripts/graph-candidates.txt", "candidate roots file")
	registry := fs.String("registry", fhirpkg.DefaultRegistryURL, "registry URL, or a directory of name-version.tgz")
	out := fs.String("o", "", "report file (default: standard output)")
	_ = fs.Parse(args)
	cands, err := readCandidates(*file)
	if err != nil {
		return err
	}
	reg := newRegistry(*registry)
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Minute)
	defer cancel()

	var b strings.Builder
	fmt.Fprintf(&b, "# Package graph report\n\n")
	fmt.Fprintf(&b, "Generated by `fhirpkg graph -candidates %s`. The report is deterministic: the same registry content gives the same text.\n\n", *file)
	fmt.Fprintf(&b, "Each candidate is the set of roots a lock would start from. The graph is explored without applying the policy, and then judged with the plan 001 rules (one core per lock, D1: a core of another series that a dependency brings is excluded and a non-core package of another series needs an exception, D2: a package in two versions is an error).\n\n")
	cache := map[string]*pkgData{}
	for _, c := range cands {
		if err := reportCandidate(ctx, &b, c, reg, cache); err != nil {
			return fmt.Errorf("%s: %w", c.label, err)
		}
	}
	if *out == "" {
		fmt.Print(b.String())
		return nil
	}
	return os.WriteFile(*out, []byte(b.String()), 0o644)
}

func reportCandidate(ctx context.Context, b *strings.Builder, c candidate, reg fhirpkg.Registry, cache map[string]*pkgData) error {
	g, err := fhirpkg.Explore(ctx, c.roots, reg, func(id string, tgz []byte) error {
		if cache[id] != nil {
			return nil
		}
		recs, st, err := fhirpkg.ReadRecords(tgz)
		if err != nil {
			return fmt.Errorf("%s: %w", id, err)
		}
		cache[id] = &pkgData{recs, st}
		return nil
	})
	if err != nil {
		// Un grafo que no se puede explorar (dependencia faltante) es un
		// hallazgo del reporte, no un fallo del comando.
		fmt.Fprintf(b, "## %s\n\nRoots: %s\n\nThe graph cannot be explored: %v\n\n", c.label, codeList(c.roots), err)
		return nil
	}
	a := g.Analyze()
	fmt.Fprintf(b, "## %s\n\nRoots: %s\n\n", c.label, codeList(g.Roots))

	fmt.Fprintf(b, "### Packages\n\n| Package | Declares FHIR | Type | .tgz (MB) | Resources | Non-semver versions | Requested by |\n|---|---|---|---|---|---|---|\n")
	for _, id := range g.IDs() {
		n := g.Nodes[id]
		declared := "(none)"
		if len(n.Manifest.FHIRVersions) > 0 {
			declared = strings.Join(n.Manifest.FHIRVersions, ", ")
			if n.Manifest.LegacyVersionList {
				declared += " (fhir-version-list)"
			}
		}
		var by []string
		for _, r := range n.Requests {
			by = append(by, orRoot(r.From))
		}
		d := cache[id]
		fmt.Fprintf(b, "| `%s` | %s | %s | %.1f | %d | %d | %s |\n", id, declared, orNone(n.Manifest.Type), float64(n.Size)/(1<<20), d.stats.Resources, d.stats.NonSemver, strings.Join(by, ", "))
	}
	b.WriteString("\n### Verdict\n\n")
	if a.Core != "" {
		fmt.Fprintf(b, "- Core: `%s` (FHIR %s, series %s).\n", a.Core, a.FHIRVersion, a.Series)
	}
	for _, p := range a.Problems {
		fmt.Fprintf(b, "- Problem: %s.\n", p)
	}
	fmt.Fprintf(b, "- Cores of another series (D1, excluded): %s.\n", listOrNone(a.ForeignCores, g))
	fmt.Fprintf(b, "- Cores of the same series as the lock's (error): %s.\n", listOrNone(a.SameSeriesCores, g))
	fmt.Fprintf(b, "- Non-core packages of another series (need an exception): %s.\n", listOrNone(a.Foreign, g))
	fmt.Fprintf(b, "- Packages that declare no FHIR version: %s.\n", listOrNone(a.Undeclared, g))
	if len(a.Doubles) == 0 {
		b.WriteString("- Packages in two versions (D2): none.\n")
	} else {
		b.WriteString("- Packages in two versions (D2, error):\n")
		for _, d := range a.Doubles {
			for _, v := range d.Versions {
				fmt.Fprintf(b, "  - `%s#%s` requested by %s\n", d.Name, v.Version, strings.Join(v.RequestedBy, ", "))
			}
		}
	}
	if len(a.Cycle) > 0 {
		fmt.Fprintf(b, "- Dependency cycle (error): %s.\n", strings.Join(a.Cycle, " -> "))
	}
	if _, err := g.Lock(fhirpkg.Options{}); err == nil {
		b.WriteString("- Lock without exceptions: valid.\n")
	} else {
		fmt.Fprintf(b, "- Lock without exceptions: error: %s.\n", oneLine(err.Error()))
		var exc []fhirpkg.Exception
		for _, id := range a.Foreign {
			exc = append(exc, fhirpkg.Exception{Package: id, Reason: "report"})
		}
		if len(a.Foreign) > 0 {
			if l, err := g.Lock(fhirpkg.Options{Exceptions: exc}); err == nil {
				fmt.Fprintf(b, "- Lock with an exception for each non-core package of another series: valid (%d packages read, %d excluded).\n", len(l.Order), len(l.Packages)-len(l.Order))
			} else {
				fmt.Fprintf(b, "- Lock with an exception for each non-core package of another series: error: %s.\n", oneLine(err.Error()))
			}
		}
	}

	recs := map[string][]fhirpkg.URLRecord{}
	for _, id := range g.IDs() {
		recs[id] = cache[id].recs
	}
	ov := fhirpkg.Overlaps(recs)
	b.WriteString("\n### URL overlaps between packages\n\n")
	if len(ov) == 0 {
		b.WriteString("No two packages publish the same canonical URL.\n\n")
		return nil
	}
	b.WriteString("Canonical URLs that two packages publish. \"Same version\" compares the `version` field; \"identical\" also compares the bytes. A version that is not semver (or is missing) cannot be ordered.\n\n")
	b.WriteString("| Package A | Package B | Shared | Same version | of which identical | Different version (both semver) | Different version (not semver) | By resource type |\n|---|---|---|---|---|---|---|---|\n")
	for _, p := range ov {
		fmt.Fprintf(b, "| `%s` | `%s` | %d | %d | %d | %d | %d | %s |\n", p.A, p.B, p.Shared, p.SameVersion, p.Identical, p.DiffSemver, p.DiffNonSemver, typeCounts(p.ByType))
	}
	b.WriteString("\n")
	return nil
}

func orRoot(from string) string {
	if from == "" {
		return "(root)"
	}
	return "`" + from + "`"
}

func orNone(s string) string {
	if s == "" {
		return "(none)"
	}
	return s
}

func codeList(ids []string) string {
	q := make([]string, len(ids))
	for i, id := range ids {
		q[i] = "`" + id + "`"
	}
	return strings.Join(q, ", ")
}

func listOrNone(ids []string, g *fhirpkg.Graph) string {
	if len(ids) == 0 {
		return "none"
	}
	parts := make([]string, len(ids))
	for i, id := range ids {
		n := g.Nodes[id]
		via := "(root)"
		if len(n.Via) > 0 {
			via = strings.Join(n.Via, " -> ")
		}
		parts[i] = fmt.Sprintf("`%s` (declares %v; via %s)", id, n.Manifest.FHIRVersions, via)
	}
	return strings.Join(parts, "; ")
}

// oneLine deja un error de varias líneas en una sola, para una viñeta.
func oneLine(s string) string {
	return strings.Join(strings.Fields(strings.ReplaceAll(s, "\n", " ")), " ")
}

func typeCounts(m map[string]int) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if m[keys[i]] != m[keys[j]] {
			return m[keys[i]] > m[keys[j]]
		}
		return keys[i] < keys[j]
	})
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%s %d", k, m[k])
	}
	return strings.Join(parts, ", ")
}
